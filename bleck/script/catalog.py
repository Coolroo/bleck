"""What a script is allowed to call, and how many arguments it takes.

Name, arity and documented signature for the game's script builtins, used to
validate calls before compiling, suggest corrections, and answer `bleck script
builtins`. Extracted from the `EVT_DECLARE_USER_FUNC` /
`EVT_UNKNOWN_USER_FUNC` declarations in MIT-licensed `spm-headers`; `bleck
script index` regenerates it from a checkout.

⚠️ The catalog describes what the *headers* document, not what a given game
version can link — a listed name can still fail to link on `kr0`. Advisory for
existence, authoritative for arity.
"""

from __future__ import annotations

import difflib
import json
import re
from dataclasses import dataclass, field
from pathlib import Path

