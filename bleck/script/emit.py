"""Writing compiled scripts out as C, for the existing REL toolchain to build.

Generating C rather than an object file directly is what lets this reuse the
whole proven path — devkitPPC, the relocatable link, `pyelf2rel` — instead of
becoming a second, parallel code generator that has to learn ELF and PowerPC
relocations by itself.

It also solves the address problem cleanly. Scripts refer to game functions by
name; the generated C declares them `extern` and takes their address, and
`elf2rel` binds each one through the symbol list at REL-build time. So no game
address is ever written by `bleck`, and no symbol list has to be redistributed
with it.
"""

from __future__ import annotations

from dataclasses import dataclass

from bleck.script.compiler import (
    CompiledProgram,
    CompiledScript,
    Literal,
    ScriptWord,
    StringWord,
    SymbolWord,
    Word,
)
from bleck.script.errors import Position, ScriptError

#: The script the loader starts. Chosen by name rather than by position so that
#: reordering a file cannot silently change which script runs.
ENTRY_SCRIPT = "main"

_PREFIX = "bleck_"

_HEADER = """\
/*
    Generated by `bleck` from {origin}.
    Do not edit: rebuild the script instead.

    This is an evt script module. The arrays below are bytecode for Super Paper
    Mario's own script VM. `_prolog` hooks the game's sequence table; the entry
    script is handed to the scheduler when gameplay starts, and re-started after
    anything that resets evt state, such as a map change.

    Game functions are referenced by name and resolved by `elf2rel` against a
    symbol list, so no addresses appear here.
*/

typedef int s32;
typedef unsigned int u32;
typedef unsigned char u8;
"""

#: Declared in every generated module, so a mod's own C can run at load time
#: without owning `_prolog` itself. Weak, so a script-only mod links with
#: nothing defining it and the call is simply skipped.
MOD_HOOK = """/*
    A mod's own C may define `mod_prolog` to run when the module loads.

    It is declared weak so a script-only module links without one. `_prolog`
    stays owned by the generated code because it has to install the sequence
    hooks first -- see the comment below for why that ordering matters.

    Anything touching live engine state belongs in a sequence hook, not here:
    at load time the game is barely up. docs/hook-points.md has the timings.
*/
__attribute__((weak)) void mod_prolog(void);
"""


_FOOTER = """
/*
    Starting the script, and keeping it started.

    `_prolog` runs the instant the loader links this module, far too early to
    hand anything to the script scheduler: the evt manager is not initialised
    yet, so `evtEntry` there does nothing at all. Hooking
    `seq_data[SEQ_GAME].init` does not work either. Both were measured, not
    guessed -- D38 and D40.

    What does work is `seq_data[SEQ_GAME].main`, verified by reading the running
    game's memory from outside the emulator: the script is created and then runs
    once per frame (D43).

    The second half is less obvious. **A script does not survive a map change** --
    evt state is torn down and rebuilt, and a script started once simply stops,
    which was measured the same way. So rather than starting once, every
    sequence other than gameplay re-arms a flag and gameplay starts the script
    whenever it is armed. That covers map changes, game overs and loads without
    needing to know which of them resets evt.
*/

typedef void(SeqFunc)(void *);

typedef struct
{{
    SeqFunc *init;
    SeqFunc *main;
    SeqFunc *exit;
}} SeqDef;

/* Resolved by name from the symbol list, like everything else here. */
extern SeqDef seq_data[];

/* spm/seqdrv.h: LOGO 0, TITLE 1, GAME 2, MAPCHANGE 3, GAMEOVER 4, LOAD 5 */
#define BLECK_SEQ_COUNT 6
#define BLECK_SEQ_GAME 2

/*
    Deliberately initialised to non-zero values so these land in .data rather
    than .bss. The loader allocates this module's bss but nothing documents
    whether it zeroes it, and depending on that would be a silent hazard.
*/
static SeqFunc *bleck_real_main[BLECK_SEQ_COUNT] = {{
    (SeqFunc *) 1, (SeqFunc *) 1, (SeqFunc *) 1,
    (SeqFunc *) 1, (SeqFunc *) 1, (SeqFunc *) 1,
}};

static u32 bleck_needs_start = 1;

static void bleck_after_seq(u32 seq, void *work)
{{
    if (seq == BLECK_SEQ_GAME)
    {{
        if (bleck_needs_start)
        {{
            bleck_needs_start = 0;
            evtEntry({entry}, 0, 0);
        }}
    }}
    else
    {{
        bleck_needs_start = 1;
    }}

    if (bleck_real_main[seq] != 0)
        bleck_real_main[seq](work);
}}

static void bleck_seq0(void *w) {{ bleck_after_seq(0, w); }}
static void bleck_seq1(void *w) {{ bleck_after_seq(1, w); }}
static void bleck_seq2(void *w) {{ bleck_after_seq(2, w); }}
static void bleck_seq3(void *w) {{ bleck_after_seq(3, w); }}
static void bleck_seq4(void *w) {{ bleck_after_seq(4, w); }}
static void bleck_seq5(void *w) {{ bleck_after_seq(5, w); }}

static SeqFunc *const bleck_hooks[BLECK_SEQ_COUNT] = {{
    bleck_seq0, bleck_seq1, bleck_seq2,
    bleck_seq3, bleck_seq4, bleck_seq5,
}};

void _prolog(void)
{{
    u32 i;

    for (i = 0; i < BLECK_SEQ_COUNT; i++)
    {{
        bleck_real_main[i] = seq_data[i].main;
        seq_data[i].main = bleck_hooks[i];
    }}

    if (mod_prolog != 0)
        mod_prolog();
}}

void _epilog(void)
{{
}}

void _unresolved(void)
{{
}}
"""


#: For a mod that ships only native sources. No script means no scheduler
#: hand-off and nothing to hook, so `_prolog` does one thing.
BARE_FOOTER = """
void _prolog(void)
{
    if (mod_prolog != 0)
        mod_prolog();
}

void _epilog(void)
{
}

void _unresolved(void)
{
}
"""


@dataclass(frozen=True)
class GeneratedSource:
    """C source for a compiled program, plus what it needs from the linker."""

    text: str
    entry_script: str
    external_symbols: list[str]

    @property
    def line_count(self) -> int:
        return len(self.text.splitlines())


def _c_string(text: str) -> str:
    """Escape a Python string as a C string literal.

    Non-ASCII is escaped byte-wise from UTF-8 rather than emitted raw, so the
    generated file stays pure ASCII and cannot be re-encoded by an editor into
    something the compiler reads differently.
    """
    out = ""
    for byte in text.encode("utf-8"):
        char = chr(byte)
        if char == "\\":
            out += "\\\\"
        elif char == '"':
            out += '\\"'
        elif char == "\n":
            out += "\\n"
        elif char == "\t":
            out += "\\t"
        elif char == "\r":
            out += "\\r"
        elif 0x20 <= byte < 0x7F:
            out += char
        else:
            # Octal, not hex: a hex escape in C consumes every following hex
            # digit, so "\x41" followed by a literal 'B' would parse as one
            # oversized escape. Octal is capped at three digits.
            out += f"\\{byte:03o}"
    return f'"{out}"'


def _word_text(word: Word) -> str:
    if isinstance(word, Literal):
        return str(word.value)
    if isinstance(word, SymbolWord):
        return f"(s32) &{word.name}"
    if isinstance(word, StringWord):
        return f"(s32) {_PREFIX}string_{word.index}"
    if isinstance(word, ScriptWord):
        return f"(s32) {_PREFIX}script_{word.name}"
    raise TypeError(f"unknown word type {type(word).__name__}")


def _script_array(script: CompiledScript) -> str:
    lines = [
        f"/* {script.name}: {len(script.words)} words, "
        f"{script.slots_used} of 16 local slots used */",
        f"const s32 {_PREFIX}script_{script.name}[] = {{",
    ]
    # Four per line: enough to be compact, few enough that a diff points at a
    # small region when bytecode changes.
    row: list[str] = []
    for word in script.words:
        row.append(_word_text(word))
        if len(row) == 4:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("};")
    return "\n".join(lines)


def generate_bare(origin: str = "native sources") -> GeneratedSource:
    """Scaffolding for a mod that ships only native C.

    The REL format still needs its three entry points, and the mod still needs
    somewhere to be called from, but there is no script to schedule.
    """
    text = _HEADER.format(origin=origin) + "\n" + MOD_HOOK + BARE_FOOTER
    _require_ascii(text)
    return GeneratedSource(text=text, entry_script="", external_symbols=[])


def generate(program: CompiledProgram, origin: str = "a script") -> GeneratedSource:
    """Render a compiled program as a single C translation unit."""
    entry = _entry_script(program)

    parts = [_HEADER.format(origin=origin)]

    if program.called_symbols:
        parts.append(
            "/* Game functions called by USER_FUNC, bound by elf2rel. */\n"
            + "\n".join(f"extern void {name}(void);" for name in program.called_symbols)
        )

    parts.append(
        "/* Started by the game's script scheduler. */\n"
        "extern void *evtEntry(const s32 *script, u32 priority, u8 flags);"
    )
    parts.append(MOD_HOOK)

    if program.strings:
        parts.append(
            "\n".join(
                f"static const char {_PREFIX}string_{index}[] = {_c_string(text)};"
                for index, text in enumerate(program.strings)
            )
        )

    if len(program.scripts) > 1:
        # Scripts may spawn each other in any order, so every array is declared
        # before any is defined.
        parts.append(
            "\n".join(
                f"extern const s32 {_PREFIX}script_{script.name}[];"
                for script in program.scripts
            )
        )

    parts.extend(_script_array(script) for script in program.scripts)
    parts.append(_FOOTER.format(entry=f"{_PREFIX}script_{entry}"))

    text = "\n\n".join(parts)
    _require_ascii(text)
    return GeneratedSource(
        text=text,
        entry_script=entry,
        external_symbols=list(program.called_symbols),
    )


def _require_ascii(text: str) -> None:
    """Guard the invariant that generated C is pure ASCII.

    Mods get built on Linux, macOS and Windows, whose compilers and editors do
    not agree on a default source encoding. String contents are already escaped
    byte-wise, so the only way a non-ASCII character reaches here is a comment
    template in this module -- which is a `bleck` bug, and better caught during
    generation than as a mojibake comment in someone else's build log.
    """
    try:
        text.encode("ascii")
    except UnicodeEncodeError as exc:
        offending = text[exc.start : exc.end]
        raise ValueError(
            f"generated C contains non-ASCII {offending!r}; "
            "this is a bug in bleck's code templates"
        ) from exc


def _entry_script(program: CompiledProgram) -> str:
    names = [script.name for script in program.scripts]
    if ENTRY_SCRIPT in names:
        return ENTRY_SCRIPT
    listed = ", ".join(names)
    raise ScriptError(
        f"no script named {ENTRY_SCRIPT!r} to start "
        f"(this file declares: {listed}). "
        f"Rename one to {ENTRY_SCRIPT!r}, or spawn the others from it",
        Position(),
    )
