#: The on-screen label naming the loaded mod.
#:
#: Every call mirrors `spm-rel-loader`'s title-screen example, which is the only
#: known-working use of this API: start, style, measure, draw -- and draw
#: *before* delegating to the real sequence main.
BANNER_BLOCK = """
/*
    Naming the loaded mod on screen.

    Text is drawn in screen space, which is centred with y increasing upward:
    `spm-rel-loader` centres a string with `x = -(width / 2)` and places it near
    the top of the title screen with `y = 200`. So the visible area is roughly
    x -320..320 and y -240..240, and the bottom-right corner is (+320, -240).
    The margins below back off from that corner far enough to survive overscan.

    `FontGetMessageWidth` measures the string so it can be right-aligned rather
    than positioned by guesswork, which also keeps a long mod name on screen.
*/

extern void FontDrawStart(void);
extern void FontDrawEdge(void);
extern void FontDrawColor(u8 *color);
extern void FontDrawScale(float scale);
extern void FontDrawNoiseOff(void);
extern void FontDrawRainbowColorOff(void);
extern void FontDrawString(float x, float y, const char *text);
extern unsigned short FontGetMessageWidth(const char *text);

#define BLECK_BANNER_RIGHT 296.0f
#define BLECK_BANNER_BOTTOM (-200.0f)
#define BLECK_BANNER_SCALE 0.6f

static const char bleck_banner_text[] = {text};

/* wii/gx.h GXColor, four bytes. Not const: FontDrawColor overwrites alpha. */
static u8 bleck_banner_color[4] = {{255, 255, 255, 255}};

/* Which sequences draw it. .rodata, so the loader's bss handling is moot. */
static const u8 bleck_banner_on[BLECK_SEQ_COUNT] = {{{flags}}};

static void bleck_draw_banner(void)
{{
    float width;

    FontDrawStart();
    FontDrawEdge();
    FontDrawColor(bleck_banner_color);
    FontDrawScale(BLECK_BANNER_SCALE);
    FontDrawNoiseOff();
    FontDrawRainbowColorOff();

    width = (float) FontGetMessageWidth(bleck_banner_text) * BLECK_BANNER_SCALE;
    FontDrawString(BLECK_BANNER_RIGHT - width, BLECK_BANNER_BOTTOM,
                   bleck_banner_text);
}}
"""

#: Typedefs and the saved originals. Needed by anything wanting a per-frame
#: hook -- a free-running script, a map watcher, or both.
SEQ_TABLE = """
/*
    Hooking the game's sequence table.

    `_prolog` runs the instant the loader links this module, far too early to
    hand anything to the script scheduler: the evt manager is not initialised
    yet, so `evtEntry` there does nothing at all. Hooking
    `seq_data[SEQ_GAME].init` does not work either. Both were measured, not
    guessed -- D38 and D40.

    What does work is `seq_data[SEQ_GAME].main`, verified by reading the running
    game's memory from outside the emulator: the script is created and then runs
    once per frame (D43).
*/

typedef void(SeqFunc)(void *);

typedef struct
{
    SeqFunc *init;
    SeqFunc *main;
    SeqFunc *exit;
} SeqDef;

/* Resolved by name from the symbol list, like everything else here. */
extern SeqDef seq_data[];

/* spm/seqdrv.h: LOGO 0, TITLE 1, GAME 2, MAPCHANGE 3, GAMEOVER 4, LOAD 5 */
#define BLECK_SEQ_COUNT 6
#define BLECK_SEQ_GAME 2

/*
    Deliberately initialised to non-zero values so these land in .data rather
    than .bss. The loader allocates this module's bss but nothing documents
    whether it zeroes it, and depending on that would be a silent hazard.
*/
static SeqFunc *bleck_real_main[BLECK_SEQ_COUNT] = {
    (SeqFunc *) 1, (SeqFunc *) 1, (SeqFunc *) 1,
    (SeqFunc *) 1, (SeqFunc *) 1, (SeqFunc *) 1,
};
"""

#: Starting the entry script, and keeping it started.
SCRIPT_START = """
/*
    A script does not survive a map change (D43). evt state is torn down and
    rebuilt, and a script started once simply stops. So rather than starting
    once, every sequence other than gameplay re-arms a flag and gameplay starts
    the script whenever it is armed. That covers map changes, game overs and
    loads without needing to know which of them resets evt.
*/

static u32 bleck_needs_start = 1;

static void bleck_start_entry(u32 seq)
{
    if (seq != BLECK_SEQ_GAME)
    {
        bleck_needs_start = 1;
        return;
    }
    if (bleck_needs_start)
    {
        bleck_needs_start = 0;
        evtEntry(%s, 0, 0);
    }
}
"""

#: Booting straight into a chosen map.
#:
#: Deliberately *not* a re-armed hook like `_SCRIPT_START`: this fires once, on
#: the first frame of gameplay, and never again. Re-arming it would send the
#: game back to the same map every time it left, which is a loop rather than a
#: starting point.
BOOT_BLOCK = """
/*
    Booting into a map.

    An unattended boot reaches exactly two maps -- aa4_01 then ls4_12, the
    attract demo -- and controller input cannot be injected (D48), so every
    other map used to need a human. This starts a script on the first frame of
    gameplay that asks the game to go somewhere else instead (D52).

    Note what this does *not* do: it does not try to redirect the first map
    load, which would be faster. The game is asked to change maps through its
    own `evt_seq_mapchange`, exactly as a door would, so arriving here is the
    same arrival the game performs everywhere else. Overwriting `seqWork.p0`
    before the loader reads it is the obvious shortcut and is untested; D51 is
    what happens when the map loader is handed something it did not expect.

    `bleck_boot_pending` starts at 1 rather than 0 so it lands in .data. The
    loader allocates this module's bss but nothing documents whether it zeroes
    it, and a boot map that fired only on some builds would be a miserable bug.
*/

static u32 bleck_boot_pending = 1;

static void bleck_boot_on_seq(u32 seq)
{{
    if (seq != BLECK_SEQ_GAME || bleck_boot_pending == 0)
        return;
    bleck_boot_pending = 0;
    evtEntry({script}, 0, 0);
}}
"""

#: Starting a script when a button combination is pressed.
#:
#: The reading path is measured, not assumed: `wpadGetWork()` is at `0x8023697c`
#: in the eu0 lst, `WpadWork.statuses` is at `+0x6C` with the newest sample
#: first, and `KPADStatus.buttonsHeld` is its first field (D67, D68).
COMBO_BLOCK = """
/*
    Button combinations.

    The game reads its own controller every frame, so a mod can read the same
    state. NOTE: This is not what D48 ruled out -- that was about *injecting* input
    into Dolphin from outside, for unattended tests, and says nothing about the
    game's own input. Conflating the two closed off this feature for weeks.

    Layout, all from spm-headers and confirmed against a running game:
      wpadGetWork()            spm/wpadmgr.h, returns WpadWork *
      WpadWork.statuses        +0x6C, [controller][age], newest age is 0
      KPADStatus.buttonsHeld   +0x00, and KPADStatus is 0x84 bytes

    NOTE: Masks are tested with `(held & mask) == mask`, never `held == mask`.
    Bit 31 of `buttonsHeld` flips between frames while the controller is
    untouched -- measured in D67 -- so an equality test would match on roughly
    half the frames and read as flaky hardware.

    Edge-triggered: a combination fires once when it becomes held, not sixty
    times a second while it stays held.
*/

extern void *wpadGetWork(void);

#define BLECK_WPAD_STATUSES 0x6C
#define BLECK_COMBO_COUNT {count}

static const u32 bleck_combo_masks[BLECK_COMBO_COUNT] = {{
{masks}}};

static const s32 *const bleck_combo_scripts[BLECK_COMBO_COUNT] = {{
{scripts}}};

/*
    Which combinations were held last frame, one bit each.

    Starts all-ones for two reasons: it is non-zero, so it lands in .data rather
    than .bss whose zeroing the loader does not document -- and it means every
    combination counts as already-held until it has been seen released. A button
    held while the game boots therefore cannot fire anything.
*/
static u32 bleck_combo_down = 0xFFFFFFFFu;

static u32 bleck_buttons_held(void)
{{
    u8 *work = (u8 *) wpadGetWork();

    /* Null before wpadInit has run; reading through it would fault. */
    if (work == 0)
        return 0;
    return *(volatile u32 *) (work + BLECK_WPAD_STATUSES);
}}

static void bleck_combos_on_seq(u32 seq)
{{
    u32 held, i, bit;

    /* evtEntry needs the script VM, which needs gameplay. Watching earlier is
       tempting and is what hung the game in D65. */
    if (seq != BLECK_SEQ_GAME)
        return;

    held = bleck_buttons_held();
    for (i = 0; i < BLECK_COMBO_COUNT; i++)
    {{
        bit = 1u << i;
        if ((held & bleck_combo_masks[i]) == bleck_combo_masks[i])
        {{
            if ((bleck_combo_down & bit) == 0)
            {{
                bleck_combo_down |= bit;
                evtEntry(bleck_combo_scripts[i], 0, 0);
            }}
        }}
        else
        {{
            bleck_combo_down &= ~bit;
        }}
    }}
}}
"""

#: Starting several mods' entry scripts, when a disc merges more than one.
#:
#: The single-mod form above is kept rather than replaced, so a disc holding one
#: mod emits exactly what it always has. A loop over one element would behave
#: identically and produce a different file, and "the output changed but only
#: cosmetically" is a claim nobody can check cheaply.
SCRIPT_START_MANY = """
/*
    Entry scripts, one per mod sharing this module.

    Each mod's `main` is started, and all of them are re-armed together: they
    are all torn down by the same map change, so there is nothing to track
    separately (D43).
*/

#define BLECK_ENTRY_COUNT {count}

static const s32 *const bleck_entries[BLECK_ENTRY_COUNT] = {{
{entries}}};

static u32 bleck_needs_start = 1;

static void bleck_start_entry(u32 seq)
{{
    u32 i;

    if (seq != BLECK_SEQ_GAME)
    {{
        bleck_needs_start = 1;
        return;
    }}
    if (bleck_needs_start)
    {{
        bleck_needs_start = 0;
        for (i = 0; i < BLECK_ENTRY_COUNT; i++)
            evtEntry(bleck_entries[i], 0, 0);
    }}
}}
"""

