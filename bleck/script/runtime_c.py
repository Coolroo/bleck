"""The C that `bleck` generates into every mod: the bleck runtime.

Separated from `emit.py` because it is *data*, not logic — nearly five hundred
lines of C source that happens to live in Python strings. Keeping it here means
`emit.py` reads as what it is, an assembler of these pieces, and means a change
to the generated runtime shows up in a diff of one file whose whole purpose is
the runtime.

Every template is a `str.format` pattern, so literal braces are doubled. The
generated output must be pure ASCII: `emit._require_ascii` fails the build
otherwise, and it has caught a stray unicode character in a comment here twice.
"""

from __future__ import annotations

HEADER = """\
/*
    Generated by `bleck` from {origin}.
    Do not edit: rebuild the script instead.

    This is an evt script module. The arrays below are bytecode for Super Paper
    Mario's own script VM. `_prolog` hooks the game's sequence table; the entry
    script is handed to the scheduler when gameplay starts, and re-started after
    anything that resets evt state, such as a map change.

    Game functions are referenced by name and resolved by `elf2rel` against a
    symbol list, so no addresses appear here.
*/

typedef int s32;
typedef unsigned int u32;
typedef unsigned char u8;
"""

#: Defined in every generated module, so a mod's own C can run at load time
#: without owning `_prolog` itself. Weak, so a mod that supplies its own
#: strong definition overrides this empty one at link time.
MOD_HOOK = """/*
    A mod's own C may define `mod_prolog` to run when the module loads.

    This is a weak *definition* rather than a declaration, and the difference
    matters: a weak declaration leaves an undefined symbol, and `elf2rel` tries
    to resolve every undefined symbol against the game's list. `mod_prolog` is
    not a game function, so a script-only mod failed to build with
    "Missing 1 required symbol(s): mod_prolog". Defining it here means there is
    nothing left undefined, and a mod that supplies its own strong definition
    overrides this one at link time.

    `_prolog` stays owned by the generated code because it has to install the
    sequence hooks first -- see the comment below for why that ordering matters.

    Anything touching live engine state belongs in a sequence hook, not here:
    at load time the game is barely up. docs/hook-points.md has the timings.
*/
__attribute__((weak)) void mod_prolog(void)
{
}
"""


#: Running a script when a named map is reached.
#:
#: ⛔ This does *not* patch `MapData.initScript`, which was the obvious design
#: and does not work: it deadlocks the map loader (D51). Instead the sequence
#: hook watches where the game says it is going, and starts the script once
#: gameplay resumes -- both mechanisms already verified in D43.
MAP_BLOCK = """
/*
    Map hooks.

    The game announces where it is going: during a map change, `seqWork.p0`
    holds the destination map's name. So arriving somewhere is observable
    without touching the game's own data at all -- the sequence hook notes the
    name on the way in, and starts the script once gameplay resumes.

    RULED OUT: patching `MapData.initScript` to chain the map's own script.
    It deadlocks -- the load freezes partway and never completes, whether the
    original is spawned blocking or detached. Measured, not guessed; see D51.

    Both halves of what is used instead are already proven: `evtEntry` from
    `seq_data[SEQ_GAME].main` is exactly how every bleck script starts (D43),
    and reading `seqWork.p0` during a map change is how the destination was
    identified in the first place (D47).
*/

typedef struct
{{
    s32 seq;
    s32 stage;
    const char *p0;
    const char *p1;
}} SeqWork;

extern SeqWork seqWork;

#define BLECK_SEQ_MAPCHANGE 3
#define BLECK_MAP_COUNT {count}
{tables}
static const char *const bleck_map_names[BLECK_MAP_COUNT] = {{
{name_list}}};

static const s32 *const bleck_map_scripts[BLECK_MAP_COUNT] = {{
{script_list}}};

/*
    Which maps are waiting to start, one bit each. Set while the map change is
    still in flight and consumed when gameplay resumes, because that is the
    moment evt is alive again -- a script started during the change would be
    torn down with the rest of evt state.
*/
static u32 bleck_map_pending = 0;

/* By hand: the module links -nostdlib, so there is no strcmp to call. */
static u32 bleck_same_name(const char *a, const char *b)
{{
    u32 i;

    if (a == 0 || b == 0)
        return 0;
    for (i = 0; a[i] != 0; i++)
        if (a[i] != b[i])
            return 0;
    return b[i] == 0;
}}

static void bleck_maps_on_seq(u32 seq)
{{
    u32 i;

    if (seq == BLECK_SEQ_MAPCHANGE)
    {{
        for (i = 0; i < BLECK_MAP_COUNT; i++)
            if (bleck_same_name(seqWork.p0, bleck_map_names[i]))
                bleck_map_pending |= (1 << i);
        return;
    }}

    if (seq != BLECK_SEQ_GAME || bleck_map_pending == 0)
        return;

    for (i = 0; i < BLECK_MAP_COUNT; i++)
    {{
        if (bleck_map_pending & (1 << i))
        {{
            bleck_map_pending &= ~(1 << i);
            evtEntry(bleck_map_scripts[i], 0, 0);
        }}
    }}
}}
"""

